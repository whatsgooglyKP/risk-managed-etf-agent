"""End-to-end backtest: agent vs agent+RL vs buy-and-hold SPY, charts, HTML report."""
from __future__ import annotations

import json
import logging
from pathlib import Path

import pandas as pd

from ..config import PROJECT_ROOT, resolve
from ..pipeline import get_forecasts, get_prices
from .engine import Backtester, buy_and_hold
from .metrics import compute_metrics, format_table
from .plots import plot_drawdown, plot_equity, plot_exposure
from .report import write_html_report

log = logging.getLogger("trading_agent.backtest")


def run_suite(cfg, with_rl: bool = True, retrain_rl: bool = False, refresh: bool = False) -> dict:
    out = resolve(cfg["backtest"]["results_dir"])
    img_dir = PROJECT_ROOT / "docs" / "images"
    out.mkdir(parents=True, exist_ok=True)
    img_dir.mkdir(parents=True, exist_ok=True)
    prices = get_prices(cfg, refresh=refresh)
    fc = get_forecasts(cfg, prices, refresh=refresh)
    start, end = cfg["backtest"]["start"], cfg["backtest"]["end"]
    cap = cfg["risk"]["initial_capital"]
    cost = cfg["costs"]["slippage_bps"] + cfg["costs"]["spread_bps"] / 2
    floor = cfg["risk"]["hard_floor"]

    bt = Backtester(prices, fc, cfg, start, end)
    base = bt.run()
    first = str(base.equity.index[0].date())
    spy = buy_and_hold(prices, cfg["benchmark"], first, end, cap, cost)
    full = {"Agent (no RL)": compute_metrics(base.equity, base.trades, base.exposure, base.floor_triggers),
            "Buy & hold SPY": compute_metrics(spy, None, None)}
    full["Buy & hold SPY"]["n_trades"] = 1
    log.info("Full period:\n%s", format_table(full))

    curves = {"Agent (no RL)": base.equity, "Buy & hold SPY": spy}
    plot_equity(curves, img_dir / "equity_full.png",
                f"Out-of-sample equity, ${cap:.0f} start ({first} to {base.equity.index[-1].date()})", floor)
    plot_drawdown(curves, img_dir / "drawdown_full.png", "Drawdown")
    plot_exposure({"Agent (no RL)": base.exposure}, img_dir / "exposure_full.png", "Market exposure")

    sections = [(f"Full out-of-sample period ({first} to {base.equity.index[-1].date()})", full)]
    images = [img_dir / "equity_full.png", img_dir / "drawdown_full.png", img_dir / "exposure_full.png"]
    summary = {"full": full, "base_halted_on": base.halted_on, "base_day_trades": base.day_trades}

    if with_rl:
        from ..rl.train import load_policy, train_ppo

        model_path = resolve(cfg["rl"]["model_path"])
        if retrain_rl or not model_path.exists():
            train_ppo(prices, fc, cfg, model_path)
        policy = load_policy(cfg, model_path)
        test_start = str((pd.Timestamp(cfg["rl"]["train_end"]) + pd.Timedelta(days=1)).date())
        bt_t = Backtester(prices, fc, cfg, test_start, end)
        base_t = bt_t.run()
        rl_t = Backtester(prices, fc, cfg, test_start, end).run(policy=policy)
        spy_t = buy_and_hold(prices, cfg["benchmark"], test_start, end, cap, cost)
        test = {"Agent (no RL)": compute_metrics(base_t.equity, base_t.trades, base_t.exposure, base_t.floor_triggers),
                "Agent + RL": compute_metrics(rl_t.equity, rl_t.trades, rl_t.exposure, rl_t.floor_triggers),
                "Buy & hold SPY": compute_metrics(spy_t, None, None)}
        test["Buy & hold SPY"]["n_trades"] = 1
        log.info("RL test period:\n%s", format_table(test))
        c2 = {"Agent (no RL)": base_t.equity, "Agent + RL": rl_t.equity, "Buy & hold SPY": spy_t}
        plot_equity(c2, img_dir / "equity_rl_test.png",
                    f"RL held-out test ({test_start} onward): RL trained only on earlier data", floor)
        plot_drawdown(c2, img_dir / "drawdown_rl_test.png", "Drawdown (RL test period)")
        plot_exposure({"Agent (no RL)": base_t.exposure, "Agent + RL": rl_t.exposure},
                      img_dir / "exposure_rl_test.png", "Market exposure (RL test period)")
        sections.append((f"RL held-out test period ({test_start} onward)", test))
        images += [img_dir / "equity_rl_test.png", img_dir / "drawdown_rl_test.png",
                   img_dir / "exposure_rl_test.png"]
        summary["rl_test"] = test
        rl_t.equity.to_csv(out / "equity_rl_test.csv")
        base_t.equity.to_csv(out / "equity_base_test.csv")

    base.equity.to_csv(out / "equity_base.csv")
    spy.to_csv(out / "equity_spy.csv")
    base.trades.to_csv(out / "trades_base.csv", index=False)
    base.exposure.to_csv(out / "exposure_base.csv")
    (out / "metrics.json").write_text(json.dumps(summary, indent=2, default=str))
    md = "\n\n".join(f"### {t}\n\n{format_table(r)}" for t, r in sections)
    (PROJECT_ROOT / "docs" / "results.md").write_text(
        "# Backtest results\n\nGenerated by `trading-agent backtest`. Out-of-sample, walk-forward, "
        f"${cap:.0f} starting capital, {cost:.0f} bps cost per trade side.\n\n" + md + "\n")
    notes = [
        "Forecasts at each date use only data available at that close (walk-forward refits).",
        "Orders fill at the next open with slippage + half-spread; Alpaca charges $0 commission.",
        "Every order passes the same RiskEngine used live (floor, sizing, cash-only, PDT, drawdown).",
        "The RL policy was trained only on data before its test period and can only scale exposure down.",
    ]
    write_html_report(PROJECT_ROOT / "docs" / "report.html", sections, images, base.trades, notes)
    log.info("Report: %s", PROJECT_ROOT / "docs" / "report.html")
    return summary
